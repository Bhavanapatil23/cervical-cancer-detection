

// ── Dark mode ──
(function () {
  const saved = localStorage.getItem("cg-theme");
  if (saved) document.documentElement.setAttribute("data-theme", saved);
  document.addEventListener("DOMContentLoaded", () => {
    const btn = document.getElementById("theme-toggle");
    if (!btn) return;
    const setIcon = () => {
      const dark = document.documentElement.getAttribute("data-theme") === "dark";
      btn.textContent = dark ? "☀" : "☾";
    };
    setIcon();
    btn.addEventListener("click", () => {
      const dark = document.documentElement.getAttribute("data-theme") === "dark";
      const next = dark ? "light" : "dark";
      if (next === "light") document.documentElement.removeAttribute("data-theme");
      else document.documentElement.setAttribute("data-theme", "dark");
      localStorage.setItem("cg-theme", next === "light" ? "" : next);
      setIcon();
    });
  });
})();
 
// ── Assessment form progress ──
document.addEventListener("DOMContentLoaded", () => {
  const form = document.getElementById("assess-form");
  if (form) {
    const fields = form.querySelectorAll("input[required], select[required]");
    const fill = document.getElementById("progress-fill");
    const update = () => {
      let filled = 0;
      fields.forEach((f) => { if (f.value) filled++; });
      if (fill) fill.style.width = `${(filled / fields.length) * 100}%`;
    };
    fields.forEach((f) => f.addEventListener("input", update));
    update();
  }
 
  // ── Risk ring animation ──
  const ring = document.querySelector(".risk-ring .fill");
  if (ring) {
    const pct = parseFloat(ring.dataset.pct || "0");
    const r = ring.r.baseVal.value;
    const circumference = 2 * Math.PI * r;
    ring.style.strokeDasharray = circumference;
    ring.style.strokeDashoffset = circumference;
    requestAnimationFrame(() => {
      ring.style.strokeDashoffset = circumference - (pct / 100) * circumference;
    });
  }
 
  // ── Delete history row ──
  document.querySelectorAll("[data-delete-id]").forEach((btn) => {
    btn.addEventListener("click", async () => {
      const id = btn.dataset.deleteId;
      if (!confirm("Delete this assessment?")) return;
      const res = await fetch(`/api/delete/${id}`, { method: "DELETE" });
      const data = await res.json();
      if (data.success) {
        document.getElementById(`row-${id}`)?.remove();
      }
    });
  });
 
  // ── History search filter ──
  const search = document.getElementById("history-search");
  if (search) {
    search.addEventListener("input", () => {
      const q = search.value.toLowerCase();
      document.querySelectorAll("#history-body tr").forEach((row) => {
        row.style.display = row.dataset.name.includes(q) ? "" : "none";
      });
    });
  }
 
  // ── Email summary ──
  const emailBtn = document.getElementById("email-summary");
  if (emailBtn) {
    emailBtn.addEventListener("click", () => {
      const { patient, risk, confidence } = emailBtn.dataset;
      const subject = encodeURIComponent(`CervixGuard AI — result for ${patient}`);
      const body = encodeURIComponent(
        `Patient: ${patient}\nRisk tier: ${risk}\nModel confidence: ${confidence}\n\nGenerated by CervixGuard AI (educational tool, not a diagnosis).`
      );
      window.location.href = `mailto:?subject=${subject}&body=${body}`;
    });
  }
 
  // ── Dashboard charts ──
  const donutEl = document.getElementById("riskDonut");
  if (donutEl && window.Chart) {
    const counts = JSON.parse(donutEl.dataset.counts);
    new Chart(donutEl, {
      type: "doughnut",
      data: {
        labels: Object.keys(counts),
        datasets: [{
          data: Object.values(counts),
          backgroundColor: ["#12A870", "#DB9200", "#E24C4C"],
          borderWidth: 0,
        }],
      },
      options: { plugins: { legend: { position: "bottom", labels: { boxWidth: 10, font: { size: 11 } } } }, cutout: "68%" },
    });
  }
 
  const lineEl = document.getElementById("riskTrend");
  if (lineEl && window.Chart) {
    const points = JSON.parse(lineEl.dataset.points);
    new Chart(lineEl, {
      type: "line",
      data: {
        labels: points.map((p) => p.date),
        datasets: [{
          data: points.map((p) => p.value),
          borderColor: "#7C3AED",
          backgroundColor: "rgba(124,58,237,0.08)",
          fill: true,
          tension: 0.35,
          pointRadius: 3,
        }],
      },
      options: { plugins: { legend: { display: false } }, scales: { y: { beginAtZero: true } } },
    });
  }
});
 
